"""Semantic search (optional, off by default: `semantic_search`): what a library item or a NeuralCore entry is about, as
a vector (pgvector), so the library can be searched by meaning. One row per item or entry, made in the background
(scene/semantic.py) and again when its words change (`digest`).

pgvector is not a trusted extension: a superuser makes it (on Azure Flexible Server, its admin, once VECTOR is allowed
in azure.extensions). This migration makes the table when the extension is there, or can be made by this account; on
a server without pgvector (LUFI's PostgreSQL 18 today) it says so and makes nothing, and semantic search stays off.
After pgvector is installed: CREATE EXTENSION vector (as a superuser), then `migrate.py downgrade 0010` and
`migrate.py upgrade`.

Revision 0011, after 0010. Made 2026-11-10."""

from alembic import op

from scene.schema import sql

revision = "0011"
down_revision = "0010"
branch_labels = None
depends_on = None

DIMENSIONS = 1024   # voyage-3.5 and voyage-3-large give 1024; Azure OpenAI's text-embedding-3 models are asked for 1024
OWN_ROWS = ("current_setting('app.user_id', true) = 'all' OR user_id = (CASE WHEN current_setting('app.user_id', true) "
            "~ '^[0-9]+$' THEN current_setting('app.user_id', true)::bigint END)")


def _one(statement):
    return op.get_bind().connection.driver_connection.execute(statement).fetchone()


def upgrade():
    if not _one("SELECT 1 FROM pg_extension WHERE extname = 'vector'"):
        if not _one("SELECT 1 FROM pg_available_extensions WHERE name = 'vector'"):
            print("0011: pgvector is not installed on this PostgreSQL: no embeddings table, semantic search stays off.")
            return
        sql("SAVEPOINT vector_extension")
        try:
            sql("CREATE EXTENSION vector")
        except Exception as error:   # pgvector is not trusted: a superuser makes it
            sql("ROLLBACK TO SAVEPOINT vector_extension")
            print("0011: pgvector is installed but this account may not make it ({}): as a superuser, CREATE EXTENSION "
                  "vector; then migrate.py downgrade 0010 and upgrade. Semantic search stays off.".format(
                      str(error).splitlines()[0]))
            return
    sql("""
    CREATE TABLE embeddings (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        generation_id BIGINT UNIQUE REFERENCES generations(id) ON DELETE CASCADE,   -- a library item
        asset_id BIGINT UNIQUE REFERENCES assets(id) ON DELETE CASCADE,             -- or a NeuralCore entry
        model TEXT NOT NULL,                  -- what made the vector (a new model makes them all again)
        digest TEXT NOT NULL,                 -- the MD5 of the words it was made from: made again when they change
        embedding vector({}) NOT NULL,
        created TIMESTAMPTZ NOT NULL DEFAULT now(),
        CHECK ((generation_id IS NULL) <> (asset_id IS NULL))
    )""".format(DIMENSIONS))
    sql("CREATE INDEX embeddings_nearest ON embeddings USING hnsw (embedding vector_cosine_ops)")
    sql("CREATE INDEX embeddings_user ON embeddings (user_id)")
    sql("ALTER TABLE embeddings ENABLE ROW LEVEL SECURITY")
    sql("ALTER TABLE embeddings FORCE ROW LEVEL SECURITY")
    sql("CREATE POLICY own_rows ON embeddings USING ({0}) WITH CHECK ({0})".format(OWN_ROWS))


def downgrade():
    sql("DROP TABLE IF EXISTS embeddings")   # the extension stays: it changes nothing by being there
