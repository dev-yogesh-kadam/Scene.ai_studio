"""The provider registry (backend/scene/providers/, docs/servers.md "Providers and keys"): every model service the studio
uses is a provider with one or more keys.

- `providers`: one service with one address and one adapter (`kind`: scene_provider_v1, comfyui, anthropic,
  claude_bridge). `legacy` names the row it was copied from ("endpoints:3", "claude:anthropic", "claude:bridge"), so
  this copy is made once however often it runs; '' for one added in the console.
- `provider_keys`: a provider's keys, each sealed with vault.py (ComfyUI's may be empty), shown only by its label and
  last 4 characters; its limits (max_concurrent, daily_cap in studio credits), its health (status, cooldown_until,
  last_error) and what the provider's whoami last said of it (`info`).
- `provider_models`: what each key's GET /v1/models last said (a cache, refreshed every 10 minutes, the last good
  answer kept).
- `jobs.provider_key`: the key a job ran with, for its daily cap; `jobs.provider`: provider, model, key label, the
  provider's job id and X-Request-Id, and in shadow mode what the router would have picked (never a key).

The copy, as the console showed it before: each ComfyUI server of `endpoints` becomes a comfyui provider with one key
(its api_key, already sealed; its "Jobs at once" as max_concurrent). The Claude connection (the settings
claude_connection, claude_bridge_url, claude_bridge_key, anthropic_api_key) becomes an anthropic provider (always)
and a claude_bridge provider (when it has an address or a key), with `agent_provider` naming the one the agent uses.
The last 4 characters of the copied keys are filled in at the app's start (providers.registry.seed), which can read
them. Langfuse stays in `endpoints`. Nothing is changed or dropped: `endpoints` and the settings stay as they are, and
the downgrade removes only what this adds.

Revision 0015, after 0014. Made 2026-11-13."""

