"""Conversations out of board blobs: each agent tab's conversation (the board "agent-<tab>", one JSON of up to a
megabyte rewritten at every save) becomes a row in `conversations` and one row per turn in `conversation_messages`.
A plan names the conversation it was made in (agent_plans.conversation_id).

The boards routes still answer the same JSON, built from these (scene/conversations.py), so the studio and the phone
site do not change. The board rows are kept, as they were at this migration, until a later contract migration drops
them (proposed, not made); going back down writes every conversation back into its board, so nothing said after this
is lost. Every conversation is rebuilt from the new tables and compared with its board before this commits.

Revision 0010, after 0009. Made 2026-11-10."""

from alembic import op

from scene.schema import sql

revision = "0010"
down_revision = "0009"
branch_labels = None
depends_on = None

OWN_ROWS = ("current_setting('app.user_id', true) = 'all' OR user_id = (CASE WHEN current_setting('app.user_id', true) "
            "~ '^[0-9]+$' THEN current_setting('app.user_id', true)::bigint END)")
# A conversation's JSON as its board held it: its own keys, and its turns as "runs" when it had them.
REBUILT = ("CASE WHEN c.has_runs THEN c.meta || jsonb_build_object('runs', COALESCE((SELECT jsonb_agg(m.data ORDER BY m.position) "
           "FROM conversation_messages m WHERE m.conversation_id = c.id), '[]'::jsonb)) ELSE c.meta END")


def _one(statement):
    return op.get_bind().connection.driver_connection.execute(statement).fetchone()


def upgrade():
    sql("""
    CREATE TABLE conversations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE,   -- NULL: all work, in no project
        tab TEXT NOT NULL,                                -- the agent tab's id (its board was agent-<tab>)
        meta JSONB NOT NULL DEFAULT '{}'::jsonb,          -- its own keys besides its turns: direction, folded, workflows
        has_runs BOOLEAN NOT NULL DEFAULT true,           -- whether it has a list of turns at all ("runs")
        updated TIMESTAMPTZ NOT NULL,
        CONSTRAINT conversations_tab UNIQUE NULLS NOT DISTINCT (user_id, project_id, tab)
    )""")
    sql("""
    CREATE TABLE conversation_messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,   -- for its row rule
        position INTEGER NOT NULL,                        -- its place in the conversation, from 0
        data JSONB NOT NULL,                              -- the turn as the page keeps it (one of "runs")
        state TEXT GENERATED ALWAYS AS (data->>'state') STORED
    )""")
    sql("CREATE INDEX conversation_messages_order ON conversation_messages (conversation_id, position)")
    sql("CREATE INDEX conversation_messages_proposed ON conversation_messages (user_id) WHERE state = 'proposed'")
    sql("CREATE INDEX conversations_user ON conversations (user_id, updated DESC)")
    for table in ("conversations", "conversation_messages"):
        sql("ALTER TABLE {} ENABLE ROW LEVEL SECURITY".format(table))
        sql("ALTER TABLE {} FORCE ROW LEVEL SECURITY".format(table))
        sql("CREATE POLICY own_rows ON {} USING ({}) WITH CHECK ({})".format(table, OWN_ROWS, OWN_ROWS))
    sql("ALTER TABLE agent_plans ADD COLUMN conversation_id BIGINT REFERENCES conversations(id) ON DELETE SET NULL")
    sql("CREATE INDEX agent_plans_conversation ON agent_plans (conversation_id)")

    boards = _one("SELECT count(*) FROM boards WHERE kind LIKE 'agent-%'")[0]
    turns = _one("SELECT COALESCE(sum(jsonb_array_length(data->'runs')), 0) FROM boards "
                 "WHERE kind LIKE 'agent-%' AND jsonb_typeof(data->'runs') = 'array'")[0]
    sql("""
    INSERT INTO conversations (user_id, project_id, tab, meta, has_runs, updated)
    SELECT user_id, project_id, substr(kind, 7),
           CASE WHEN jsonb_typeof(data->'runs') = 'array' THEN data - 'runs' ELSE data END,
           jsonb_typeof(data->'runs') = 'array', updated
    FROM boards WHERE kind LIKE 'agent-%'""")
    sql("""
    INSERT INTO conversation_messages (conversation_id, user_id, position, data)
    SELECT c.id, c.user_id, r.ord - 1, r.value
    FROM boards b JOIN conversations c ON c.user_id = b.user_id AND c.project_id IS NOT DISTINCT FROM b.project_id
                                      AND c.tab = substr(b.kind, 7)
    CROSS JOIN LATERAL jsonb_array_elements(b.data->'runs') WITH ORDINALITY AS r(value, ord)
    WHERE b.kind LIKE 'agent-%' AND jsonb_typeof(b.data->'runs') = 'array'""")
    sql("""
    UPDATE agent_plans p SET conversation_id = c.id FROM conversations c
    WHERE c.user_id = p.user_id AND c.project_id IS NOT DISTINCT FROM p.project_id AND c.tab = p.tab""")
    made = _one("SELECT (SELECT count(*) FROM conversations), (SELECT count(*) FROM conversation_messages)")
    differ = _one("""
    SELECT count(*) FROM boards b JOIN conversations c ON c.user_id = b.user_id
        AND c.project_id IS NOT DISTINCT FROM b.project_id AND c.tab = substr(b.kind, 7)
    WHERE b.kind LIKE 'agent-%' AND b.data <> ({})""".format(REBUILT))[0]
    if made != (boards, turns) or differ:
        raise RuntimeError("conversations: {} boards with {} turns became {} conversations with {} turns, {} not the same"
                           .format(boards, turns, made[0], made[1], differ))
    print("0010: {} conversations with {} turns, each the same as its board".format(boards, turns))


def downgrade():
    """Every conversation back into its board (updated where the board is there, made where the tab is newer); the board
    of a tab deleted since goes as well."""
    sql("""
    DELETE FROM boards b WHERE b.kind LIKE 'agent-%' AND NOT EXISTS (SELECT 1 FROM conversations c
        WHERE c.user_id = b.user_id AND c.project_id IS NOT DISTINCT FROM b.project_id AND c.tab = substr(b.kind, 7))""")
    sql("""
    INSERT INTO boards (user_id, project_id, kind, data, updated)
    SELECT c.user_id, c.project_id, 'agent-' || c.tab, {}, c.updated FROM conversations c
    ON CONFLICT (user_id, project_id, kind) DO UPDATE SET data = excluded.data, updated = excluded.updated""".format(REBUILT))
    sql("DROP INDEX agent_plans_conversation")
    sql("ALTER TABLE agent_plans DROP COLUMN conversation_id")
    sql("DROP TABLE conversation_messages")
    sql("DROP TABLE conversations")
